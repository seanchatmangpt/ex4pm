    \\textbf{P99 Tail Bottleneck Latency} & \\textbf{#{p.duration_lognormal_fit.p99_ms}} & ms \\\\
    Maximum Observed Latency & #{p.duration_lognormal_fit.max_ms} & ms \\\\
    \\bottomrule
    \\end{tabular}
    \\caption{Information-theoretic entropy and log-normal latency parameters estimated from the full 647k production OCEL 2.0 dataset.}
    \\label{tab:generated_ocel_benchmark}
