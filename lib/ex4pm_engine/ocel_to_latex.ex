  end

  defp format_activity_rows(top_activities) do
    top_activities
    |> Enum.sort_by(&elem(&1, 1), :desc)
    |> Enum.take(12)
    |> Enum.map(fn {act, count} ->
      domain = infer_domain(act)
      escaped = escape_latex(to_string(act))
      "\\texttt{#{escaped}} & #{domain} & #{count} \\\\"
    end)
    |> Enum.join("\n")
  end

  defp format_transition_rows(top_transitions) when is_list(top_transitions) do
    top_transitions
    |> Enum.take(10)
    |> Enum.map(fn {src, dst, cnt} ->
      "\\texttt{#{escape_latex(to_string(src))}} $\\to$ \\texttt{#{escape_latex(to_string(dst))}} & & #{cnt} \\\\"
    end)
    |> Enum.join("\n")
  end

  defp format_transition_rows(_), do: "% No transition data available \\\\"

  defp format_pareto_rows(pareto) when is_list(pareto) do
    pareto
    |> Enum.map(fn {act, cnt, pct} ->
      "\\texttt{#{escape_latex(to_string(act))}} & #{cnt} & #{pct}\\% \\\\"
    end)
    |> Enum.join("\n")
  end

  defp format_pareto_rows(_), do: "% No Pareto data available \\\\"

  defp escape_latex(str), do: String.replace(str, "_", "\\_")

  defp infer_domain(act) do
    str = to_string(act)

    cond do
      String.starts_with?(str, "capability_liveness") -> "Operations"
      String.starts_with?(str, "org") -> "Accounts"
      String.starts_with?(str, "account") -> "Accounts"
      String.starts_with?(str, "subscription") -> "Billing"
      String.starts_with?(str, "provider") -> "Marketplace"
      String.starts_with?(str, "incident") -> "Operations"
      String.starts_with?(str, "approval") -> "Governance"
      String.starts_with?(str, "webhook") -> "Platform"
      String.starts_with?(str, "version") -> "Platform"
      true -> "Enterprise Core"
    end
  end
end
