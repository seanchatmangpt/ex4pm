  Automated IEEE OCEL 2.0 to Publication-Grade LaTeX Table Generator.

  Parses any IEEE OCEL 2.0 NDJSON/JSON stream and formats:
  - Discovered Activity Frequencies & Enterprise Domain Breakdown
  - Object Interaction Multigraph Statistics
  - Tail Latency Percentiles (Mean, P50, P90, P99, Max)
  - Information-Theoretic Shannon Entropy H(L)
  - Stochastic Transition Probability Matrix (top N×N most frequent transitions)
  - Variant Pareto Cumulative Distribution Curve

  Outputs booktabs-formatted LaTeX snippets ready for direct inclusion into academic papers.
  """

  alias Ex4pmEngine.StochasticProfiler

  @fallback_profile %{
